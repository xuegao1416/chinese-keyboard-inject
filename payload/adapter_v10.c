/* --- the runtime font pre-check ----------------------------------------------
   A host whose own font has no CJK face still accepts our two-byte codes and
   prints Latin stand-ins in place of Hanzi, so the only trustworthy signal is
   what the glyph actually looks like once it is on screen.  The gate therefore
   prints the page into the keyboard window that is BEHIND its twin, measures it
   there, and only then decides: a host that passes enters Chinese mode, one that
   fails gets the stock page swap it asked for.  The window the user is looking at
   is never drawn into, and the buffer that is probed is put back tile for tile
   from a stash, so a refusal leaves the host's VRAM word-identical to before the
   press.
   An earlier revision measured after entry and rolled the press back, which
   showed several frames of mojibake on exactly the hosts the gate exists for; the
   probe moved off screen because of that.  The stash is what makes an off-screen
   probe safe at all - measured, a bare FillWin on the back buffer leaves the stock
   keyboard blank for the next two page swaps. */
static u8* ck_btnspr(u8*n){
    unsigned fid=(unsigned)n[CK_FID],bid;
    u8*f;
    if(fid>63u)return 0;
    f=gspr(fid);
    bid=(unsigned)f[CK_SPR_BTNID];
    if(bid>63u)return 0;
    return gspr(bid);
}
static int ck_gate_pending(u8*b){
    u16 s=*(u16*)(b+CK_GATE_STEP);
    return s!=CK_GATE_OFF&&s!=CK_GATE_UNFIT;
}
static void ck_cn_enter(void){
    u8*n=ns();if(!n)return;
    ck_set_page(0);n[NSP]=1;
    render(n[NSW]);render(n[NSW+1]);      /* both windows back to a Chinese page */
    ck_flash(3,0,0);ck_cursor_hook(0,0);CK_SE(5);
}
static void ck_gate_clear(void){
    volatile u16*d=(volatile u16*)objv16(CK_GATE_STASH);unsigned i;
    for(i=0;i<CK_GATE_WORDS;i++)d[i]=0;
}
/* Arm the probe: stash the hidden window's whole art, then print the Chinese page
   into that window.  render() takes its page from ckstate(), which is 0 while the
   lock is off, so this is the same page ck_cn_enter would show.
   0 = cannot verify this host at all, which is treated as a refusal, because
   "no CJK face" and "cannot tell" look the same from here. */
static int ck_gate_begin(u8*n,u8*b){
    u8 w;unsigned base;
    if(!CK_KB_TILEBASE||!CK_KB_WINW)return 0;
    ck_hid_kb(n,&w,&base);
    if(!ck_scratch_free(CK_GATE_STASH,CK_GATE_TILES))return 0;
    *(u16*)(b+CK_GATE_STEP)=CK_GATE_FIRST;
    *(u16*)(b+CK_GATE_PREV)=0xFFFFu;     /* "no sample taken yet" */
    ck_move_words(objv16(CK_GATE_STASH),bgv16(base),CK_GATE_WORDS);  /* art -> scratch */
    render(w);                                           /* never on screen */
    return 1;
}
/* Statistics for the whole probed page: 4 rows x 8 cells, each cell 16x16 px =
   four 8x8 tiles, the first one starting at map tile 1 (the same cell the label
   blit measures).
     zn   cells with no ink at all (not printed yet, or a blank glyph)
     wn   narrowest ink box over the printed cells
     gap  printed cells whose midline (columns 7 and 8) is completely bare
     mt   smallest single-quadrant ink over the printed cells
     sum  total ink over the page - what stops growing is what finished printing
   Why the sub-cell numbers are the point: a fontless host used to be described
   from the *visible* keyboard, where its cells measured 12 px wide with 6-8 empty
   quadrants and 3 bare midlines - close enough to a Hanzi that cell geometry
   looked unable to separate the two faces.  That surface is not what the gate
   measures: it reads its own hidden window, and there the same hosts come out
   narrower than any Hanzi.  Measured over 22 hosts on 2026-09-27 and published in
   qa/font_gate_verdicts.json (tools/read_gate_verdict.py reads it out of a GSPR
   dump of these very slots):
     carries a CJK font (5 hosts):   wn 10, mt 6, zn 0, gap 0
     no CJK font     (17 hosts):     wn  6, mt 0, zn 0, gap 0
   So on this page wn is the criterion that decides, mt agrees with it on every
   host, and zn/gap never fired alone - they stay as guards against a page that
   did not print.  A Hanzi fills its em box; a Latin stand-in keeps its
   sidebearings, and a space byte keeps its whole 8 px column empty. */
static void ck_page_stats(unsigned base,int*zn,int*wn,int*gap,int*mt,int*sum){
    unsigned W=(unsigned)CK_KB_WINW;
    int r,k,y,a,b,c,d,lft,rgt,t,n;
    int nz=0,mw=99,ng=0,mtil=64,tot=0;
    for(r=0;r<4;r++)for(k=0;k<8;k++){
        unsigned tl=base+1u+(unsigned)k*2u+(unsigned)(r*2)*W;
        int x,h,w;
        a=ck_tile_ink12(tl);b=ck_tile_ink12(tl+1u);
        c=ck_tile_ink12(tl+W);d=ck_tile_ink12(tl+W+1u);
        n=a+b+c+d;tot+=n;
        /* A cell with no ink is not evidence of anything: the printer gets one
           glyph per frame, so half the page is empty while it works.  Every
           measure below is therefore taken over printed cells only, and a verdict
           is read once the ink total stops growing (ck_gate_step). */
        if(!n){nz++;continue;}
        t=a<b?a:b;if(c<t)t=c;if(d<t)t=d;
        if(t<mtil)mtil=t;
        lft=0;rgt=0;
        for(y=0;y<16;y++){if(ck_wpx(tl,W,7,y))lft++;if(ck_wpx(tl,W,8,y))rgt++;}
        if(!lft&&!rgt)ng++;
        if(!ck_ink_box(tl,W,&x,&y,&w,&h)){nz++;continue;}
        if(w<mw)mw=w;
    }
    *zn=nz;*wn=mw;*gap=ng;*mt=mtil;*sum=tot;
}
static void ck_gate_step(u8*b){
    u8*n=ns();u8 w;unsigned base;u16 st,prev;int zn,wn,gap,mt,sum,done;
    if(!n)return;
    st=*(u16*)(b+CK_GATE_STEP);
    ck_hid_kb(n,&w,&base);
    ck_page_stats(base,&zn,&wn,&gap,&mt,&sum);
    *(u16*)(b+CK_GATE_DIAG)=(u16)(mt&0xFF);
    prev=*(u16*)(b+CK_GATE_PREV);
    if((int)prev!=sum&&st<(int)CK_GATE_MAX){
        /* the page is still being printed - look again next frame */
        *(u16*)(b+CK_GATE_PREV)=(u16)sum;
        *(u16*)(b+CK_GATE_STEP)=(u16)(st+1u);
        return;
    }
    /* Which criteria actually carry the verdict, from the slots below (22 hosts):
       a CJK face gives wn 10 / mt 6, a stand-in face wn 6 / mt 0 - width decides,
       min-quadrant agrees with it on every host, and zn/gap are 0 on both sides.
       They stay because a page that never filled in is refused too: not knowing is
       not knowing it works. */
    done=0;
    if(!zn&&mt&&wn>=(int)CK_CN_MIN_W&&!gap)done=1;
    /* Whatever the verdict, the probed buffer goes back exactly as the press found
       it before anything else happens. */
    ck_move_words(bgv16(base),objv16(CK_GATE_STASH),CK_GATE_WORDS);
    ck_gate_clear();
    *(u16*)(b+CK_GATE_STEP)=done?CK_GATE_OFF:CK_GATE_UNFIT;
    if(done)*(u16*)(b+CK_GATE_DIAG)|=CK_GATE_CJK;
    if(done){ck_cn_enter();return;}
    ((KeyHandlerFn)CK_ORIG_PAGE)(5);   /* the page swap the user asked for */
}
__attribute__((used,section(".text.lr"))) bool8 ck_handle_frame(void){
    u8*n=ns();
    {   u8*b=n?ck_btnspr(n):0;
        /* Judged before the label: the label writes into the window behind this
           one and would move the tile map out from under the measurement. */
        if(b&&ck_gate_pending(b)){ ck_gate_step(b); return 0; }
    }
    if(!n || !locked()) return ((HandleFn)CK_HANDLE_EVENT)();
    /* The Chinese label on the page-swap capsule takes three frames to build and
       must not be interrupted by input; see ck_label_step. */
    if(ck_label_pending()){ ck_label_step(); return 0; }
    /* Emerald-family gMain.newKeysRaw at gMain+0x2A. Use edge-triggered input
       already maintained by the engine instead of sampling REG_KEYINPUT. */
    u16 keys=*(volatile u16*)CK_GMAIN_NEWKEYS_RAW;
    /* SELECT is the global escape from Chinese lock. Clear private state, put the
       stock button graphics back, then let the untouched stock handler perform
       its normal page swap. */
    if(keys&0x0004){ ck_unlock(); ck_label_restore(); ck_restore_keyboard(n); return ((HandleFn)CK_HANDLE_EVENT)(); }
    u8 page=(u8)ckstate();
    if(keys&0x0200){ page=(page==0)?223:(u8)(page-1); ck_set_page(page); render(n[NSW]);render(n[NSW+1]);CK_SE(5);return 0; }
    if(keys&0x0100){ page=(page>=223)?0:(u8)(page+1); ck_set_page(page); render(n[NSW]);render(n[NSW+1]);CK_SE(5);return 0; }
    /* Everything else - D-pad movement included - goes to the stock handler. The
       cursor sprite itself is positioned by ck_cursor_hook, which the injector
       installs over every BL SetCursorPos site, so its x/y never needs fixing up
       here. */
    return ((HandleFn)CK_HANDLE_EVENT)();
}
__attribute__((used,section(".text.entry"))) bool8 ck_character_handler(u8 input){
    u8*n=ns();
    if(!locked()){
        if(!n||!ck_encoding_active(n))return ((KeyHandlerFn)CK_ORIG_CHARACTER)(input);
        ck_flash(3,0,0);
        if(input==5&&n[NSCID]<=63u){
            Spr*s=(Spr*)(CK_GSPRITES+(unsigned)n[NSCID]*0x44);
            int x=s->data[0],y=s->data[1];
            static const u8 page_ids[3]={2,1,0};
            if(x>=0&&x<8&&y>=0&&y<4&&n[NSP]<3u){
                u8 code=((const u8*)CK_KEYBOARD_DATA)[page_ids[n[NSP]]*32u+(unsigned)y*8u+(unsigned)x];
                if(cki_text_append(n+0x1800,ck_name_capacity(n),15u,code,0)){
                    ck_draw_name(n);CK_SE(5);
                }else CK_SE(0x16);
            }
        }
        return 0;
    }
    if(input==5&&ck_append_cn())CK_SE(5);
    return 0;
}
